/** Types for the leases endpoints. Source: ../property-os-api/docs/frontend-handoff/API.md sections 2 and 4 ("Lease"). */

export type LeaseStatus = "DRAFT" | "ACTIVE" | "ENDED" | "TERMINATED";

export type SignatureStatus = "NOT_SENT" | "PENDING" | "SIGNED";

export type PaymentFrequency = "WEEKLY" | "BIWEEKLY" | "MONTHLY" | "QUARTERLY";

/** One tenant on a lease. The primary tenant comes first. */
export interface LeaseTenant {
  id: string;
  fullName: string;
  email: string;
  isPrimary: boolean;
}

/** GET /leases and GET /leases/:id (LeaseResponse). */
export interface Lease {
  id: string;
  /** "LSE-2026-001", generated by the server. */
  leaseNumber: string;
  unitId: string;
  status: LeaseStatus;
  signatureStatus: SignatureStatus;
  /** "YYYY-MM-DD"; null only on DRAFT. */
  startDate: string | null;
  /** "YYYY-MM-DD"; null only on DRAFT. */
  endDate: string | null;
  paymentFrequency: PaymentFrequency;
  /** Money string; null only on DRAFT. */
  rent: string | null;
  /** Money string; null only on DRAFT. */
  deposit: string | null;
  /** Money string, default "0". */
  lateFeeAmount: string;
  lateFeeGraceDays: number;
  /** 1–31; null only on DRAFT. */
  rentDueDay: number | null;
  autoRenew: boolean;
  tags: string[];
  notes: string | null;
  createdById: string;
  /** ISO timestamp. */
  createdAt: string;
  /** ISO timestamp. */
  updatedAt: string;
  unit: { id: string; unitNumber: string; property: { id: string; name: string } };
  /** Primary first; [] when none. */
  tenants: LeaseTenant[];
  /** Whole months, end date inclusive; null if a date is missing. */
  termMonths: number | null;
  /** ACTIVE and endDate within the next 30 days (UTC). */
  endingSoon: boolean;
  /** Money string (fixed 2), all time; negative = credit. */
  balance: string;
  /** "YYYY-MM-DD" or null. */
  oldestUnpaidDueDate: string | null;
}

/**
 * POST /leases body (../property-os-api/docs/frontend-handoff/API.md section 5). Only unitId is required for a DRAFT; status "ACTIVE" runs the activation checks.
 * Money is a JSON number (max 2 decimals). Never send null on create.
 */
export interface LeaseCreateBody {
  unitId: string;
  status?: "DRAFT" | "ACTIVE";
  signatureStatus?: SignatureStatus;
  startDate?: string;
  endDate?: string;
  paymentFrequency?: PaymentFrequency;
  rent?: number;
  deposit?: number;
  lateFeeAmount?: number;
  lateFeeGraceDays?: number;
  rentDueDay?: number;
  autoRenew?: boolean;
  tags?: string[];
  notes?: string;
  primaryTenantId?: string;
  coTenantIds?: string[];
}

/**
 * PATCH /leases/:id body: any subset, never status. unitId only while DRAFT.
 * null clears startDate, endDate, rent, deposit, rentDueDay, notes and primaryTenantId (never send it on an ACTIVE lease).
 */
export type LeaseUpdateBody = Partial<
  Omit<LeaseCreateBody, "status" | "startDate" | "endDate" | "rent" | "deposit" | "rentDueDay" | "notes" | "primaryTenantId">
> & {
  startDate?: string | null;
  endDate?: string | null;
  rent?: number | null;
  deposit?: number | null;
  rentDueDay?: number | null;
  notes?: string | null;
  primaryTenantId?: string | null;
};

/** POST /leases/:id/end body. Default ENDED. */
export interface LeaseEndBody {
  status?: "ENDED" | "TERMINATED";
}
